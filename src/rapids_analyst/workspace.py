"""Per-run workspace: the shared state between agents. Files, not chat."""
from __future__ import annotations

import json
import shutil
import time
import uuid
from pathlib import Path
from typing import Any


class Workspace:
    def __init__(self, root: Path):
        self.root = root
        self.root.mkdir(parents=True, exist_ok=True)
        (self.root / "input").mkdir(exist_ok=True)
        (self.root / "figures").mkdir(exist_ok=True)
        (self.root / "_steps").mkdir(exist_ok=True)
        self._step_counter = 0

    @classmethod
    def create(cls, base: Path, dataset: Path) -> "Workspace":
        run_id = time.strftime("%Y%m%d-%H%M%S") + "-" + uuid.uuid4().hex[:6]
        ws = cls(base / run_id)
        shutil.copy(dataset, ws.input_dir / dataset.name)
        return ws

    # -- paths ---------------------------------------------------------
    @property
    def input_dir(self) -> Path:
        return self.root / "input"

    def path(self, name: str) -> Path:
        return self.root / name

    def dataset_path(self) -> Path:
        files = sorted(p for p in self.input_dir.iterdir() if p.is_file())
        if not files:
            raise FileNotFoundError("No dataset in workspace input/")
        return files[0]

    # -- json helpers --------------------------------------------------
    def write_json(self, name: str, obj: Any) -> None:
        self.path(name).write_text(json.dumps(obj, indent=2, default=str))

    def read_json(self, name: str) -> Any:
        return json.loads(self.path(name).read_text())

    def exists(self, name: str) -> bool:
        return self.path(name).exists()

    # -- trace + step ledger ------------------------------------------
    def trace(self, event: str, **fields: Any) -> None:
        rec = {"t": time.time(), "event": event, **fields}
        with open(self.path("trace.jsonl"), "a") as f:
            f.write(json.dumps(rec, default=str) + "\n")

    def next_step_path(self, agent: str) -> Path:
        self._step_counter += 1
        return self.root / "_steps" / f"{self._step_counter:02d}_{agent}.py"

    def record_fallback(self, agent: str, detail: str) -> None:
        fb = self.read_json("fallbacks.json") if self.exists("fallbacks.json") else []
        fb.append({"agent": agent, "detail": detail})
        self.write_json("fallbacks.json", fb)

    def export_analysis_py(self, successful_steps: list[Path]) -> None:
        """Concatenate every successful generated step into one reproducible script."""
        parts = ["# Auto-generated by rapids-analyst. Steps run in order.\n"]
        for p in successful_steps:
            parts.append(f"\n# ===== {p.name} =====\n{p.read_text()}\n")
        self.path("analysis.py").write_text("".join(parts))
